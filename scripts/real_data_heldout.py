"""Held-out-perturbation prediction on real data: Norman et al. 2019 (CRISPRa Perturb-seq, K562), single-gene perturbations.

    python scripts/real_data_heldout.py [--h5ad data/downloads/norman/perturb_processed.h5ad] [--out docs/results/real_data_heldout]

The same predictors and metrics as the simulated benchmark (``grn_sim.evaluation.heldout_screen``), but the response of a
perturbation is its observed mean shift of log-normalised expression against the control cells, for the training and for the
held-out perturbations alike: real data have no noise-free truth, so the scores here are lower bounds and are only comparable
between predictors. A gene counts as moved when its shift is at least ``--threshold`` (default 0.15 log units).
Needs the file from ``scripts/download_data.py --norman`` (not shipped); ``anndata`` must be installed.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from types import SimpleNamespace

import numpy as np

from grn_sim.evaluation.heldout_screen import METRICS, PREDICTORS, evaluate_heldout


def load_responses(path: Path, min_cells: int = 30):
    import anndata
    from scipy import sparse

    ad = anndata.read_h5ad(path)
    X = ad.X.tocsr() if sparse.issparse(ad.X) else sparse.csr_matrix(ad.X)
    genes = list(ad.var["gene_name"].astype(str)) if "gene_name" in ad.var else list(ad.var_names)
    index = {g: i for i, g in enumerate(genes)}
    cond = ad.obs["condition"].astype(str).to_numpy()
    ctrl = np.asarray(X[cond == "ctrl"].mean(axis=0)).ravel()
    nodes, rows, cells = [], [], []
    for c in sorted(set(cond)):
        if not c.endswith("+ctrl"):
            continue
        g = c[: -len("+ctrl")]
        sel = cond == c
        if g not in index or sel.sum() < min_cells:
            continue
        nodes.append(index[g])
        rows.append(np.asarray(X[sel].mean(axis=0)).ravel() - ctrl)
        cells.append(int(sel.sum()))
    return np.array(nodes), np.stack(rows), genes, cells


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--h5ad", default="data/downloads/norman/perturb_processed.h5ad")
    ap.add_argument("--out", default="docs/results/real_data_heldout")
    ap.add_argument("--threshold", type=float, default=0.15)
    ap.add_argument("--seeds", type=int, default=10)
    a = ap.parse_args()
    nodes, R, genes, cells = load_responses(Path(a.h5ad))
    n = R.shape[1]
    screen = SimpleNamespace(conditions=[(int(g),) for g in nodes], total_effects=R.T, effect_threshold=a.threshold, n_genes=n)
    ace = SimpleNamespace(nodes=nodes, lfc=R)
    runs = [evaluate_heldout(screen, ace, n_folds=5, seed=s, threshold=a.threshold) for s in range(a.seeds)]
    info = {"perturbations": len(nodes), "genes": n, "cells_per_perturbation_median": float(np.median(cells)), "threshold": a.threshold,
            "seeds": a.seeds}
    out = Path(a.out)
    out.with_suffix(".json").write_text(json.dumps({"info": info, "runs": runs}, indent=1) + "\n")
    out.with_suffix(".md").write_text(render(info, runs))
    print("wrote", out.with_suffix(".md"))
    return 0


def _ms(vals):
    v = np.array([x for x in vals if np.isfinite(x)], dtype=float)
    return "-" if not len(v) else f"{v.mean():.3f} ± {v.std(ddof=1) if len(v) > 1 else 0.0:.3f}"


def render(info, runs) -> str:
    L = ["# Held-out perturbation prediction on real data (Norman et al. 2019)", "",
         "Generated by `scripts/real_data_heldout.py`. Single-gene CRISPRa perturbations of the K562 screen "
         f"({info['perturbations']} perturbations with at least 30 cells, {info['genes']} genes, median {info['cells_per_perturbation_median']:.0f} cells each). "
         "The response of a perturbation is its observed mean shift of log-normalised expression against control cells, for training and held-out "
         f"perturbations alike, so there is no noise-free truth and the scores are lower bounds. A gene counts as moved at a shift of {info['threshold']}. "
         f"5-fold cross-validation over perturbations, mean ± sd over {info['seeds']} fold assignments. Predictors and metrics are described in "
         "`grn_sim.evaluation.heldout_screen`.", "",
         "| predictor | stratum | " + " | ".join(METRICS) + " |", "|---|---|" + "---|" * len(METRICS)]
    for m in PREDICTORS:
        for st in ("all", "active"):
            L.append(f"| {m} | {st} | " + " | ".join(_ms([r[m][st][k] for r in runs]) for k in METRICS) + " |")
    L.append("")
    L.append(f"Held-out perturbations that moved at least one gene: {runs[0]['control']['active']['n']} of {runs[0]['n_perturbations']}.")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
