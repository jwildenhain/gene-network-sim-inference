"""Per-algorithm statistics over the simulation archive: docs/results/archive_leaderboard.md.

``snapshot`` reads the archive (read-only) into ``docs/results/archive_leaderboard.json``; ``render`` writes the page from it;
``tests/test_archive_leaderboard_doc.py`` fails when they differ. Every algorithm of the registry is listed in every size group
(the archive was cleaned so that each run has all of them, ``scripts/clean_archive.py --verify``).

    python scripts/render_archive_leaderboard.py snapshot data/rgn_db.sqlite
    python scripts/render_archive_leaderboard.py render
    python scripts/render_archive_leaderboard.py --check
"""
import argparse
import json
import sqlite3
import statistics as st
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
SNAPSHOT = ROOT / "docs" / "results" / "archive_leaderboard.json"
PAGE = ROOT / "docs" / "results" / "archive_leaderboard.md"
GROUPS = [("small", "up to 16 genes", 0, 16), ("medium", "17 to 266 genes", 17, 266), ("500", "500 genes", 500, 500),
          ("1000", "1000 genes", 1000, 1000)]
CONTROLS = ("by_chance", "gene_features")


def _mean(x: List[float]) -> float:
    return st.mean(x) if x else float("nan")


def snapshot(db: Path) -> Dict[str, Any]:
    from grn_sim.web.database import unpack_json
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    per: Dict[str, Dict[str, Dict[str, List[float]]]] = {g[0]: {} for g in GROUPS}
    runs = {g[0]: 0 for g in GROUPS}
    for simid, nz, raw in con.execute("SELECT simid, nz, inferred_payload_json FROM nw").fetchall():
        group = next((g[0] for g in GROUPS if g[2] <= nz <= g[3]), None)
        metrics = json.loads(unpack_json(raw) or "{}").get("metrics", {}) if raw and len(raw) > 2 else {}
        if group is None or not metrics:
            continue
        runs[group] += 1
        for alg, m in metrics.items():
            d = per[group].setdefault(alg, {"f1": [], "recall": [], "precision": [], "aupr": [], "errors": [], "seconds": []})
            d["f1"].append(float(m.get("f1_score", 0.0)))
            d["recall"].append(float(m.get("recall", 0.0)))
            d["precision"].append(float(m.get("precision", 0.0)))
            if isinstance(m.get("aupr"), (int, float)):
                d["aupr"].append(float(m["aupr"]))
            d["errors"].append(float(m.get("total_errors", 0)))
            d["seconds"].append(float(m.get("runtime_ms", 0.0)) / 1000.0)
    out: Dict[str, Any] = {"groups": {g[0]: {"label": g[1], "runs": runs[g[0]], "algorithms": {}} for g in GROUPS}}
    for g, algs in per.items():
        for alg, d in algs.items():
            out["groups"][g]["algorithms"][alg] = {
                "runs": len(d["f1"]), "f1": round(_mean(d["f1"]), 3), "f1_sd": round(st.stdev(d["f1"]), 3) if len(d["f1"]) > 1 else 0.0,
                "recall": round(_mean(d["recall"]), 3), "precision": round(_mean(d["precision"]), 3),
                "aupr": round(_mean(d["aupr"]), 3) if d["aupr"] else None, "aupr_runs": len(d["aupr"]),
                "errors": round(_mean(d["errors"]), 1), "seconds": round(st.median(d["seconds"]), 3)}
    return out


def render(snap: Dict[str, Any]) -> str:
    L = ["# Inference on the simulation archive: every algorithm, by network size", "",
         "Generated by `scripts/render_archive_leaderboard.py` from `docs/results/archive_leaderboard.json`, a snapshot of the "
         "simulation archive (`rgn_db.sqlite`); `tests/test_archive_leaderboard_doc.py` fails when the page and the snapshot differ. "
         "After the clean-up of 2026-11-13 (`scripts/clean_archive.py`) every archived run holds a result for every algorithm.", "",
         "Columns: *F1*, *recall*, *precision*: mean over runs at the algorithm's own edge count (± SD for F1); *AUPR*: mean over the "
         "runs that stored it (rescored runs may lack it); *errors*: mean total errors; *median s*: median run time of the "
         "algorithm on one network. Controls (`by_chance`, `gene_features`) are listed last. Runs differ in topology, noise, "
         "perturbation model and parameters; they are pooled within a size group, so the SD mixes network and seed variation. "
         "Rows were stored over several days of code changes (the archive keeps no code version per row).", ""]
    for key in [g[0] for g in GROUPS]:
        g = snap["groups"][key]
        algs = g["algorithms"]
        if not algs:
            continue
        L += [f"## {g['label']} ({g['runs']} runs)", "",
              "| # | algorithm | runs | F1 | recall | precision | AUPR | errors | median s |", "|---|---|---|---|---|---|---|---|---|"]
        order = sorted((a for a in algs if a not in CONTROLS), key=lambda a: (-algs[a]["f1"], a)) + sorted(a for a in algs if a in CONTROLS)
        for i, a in enumerate(order, 1):
            d = algs[a]
            aupr = "-" if d["aupr"] is None else f"{d['aupr']:.3f}" + ("" if d["aupr_runs"] == d["runs"] else f" ({d['aupr_runs']})")
            L.append(f"| {i if a not in CONTROLS else '-'} | {a} | {d['runs']} | {d['f1']:.3f} ± {d['f1_sd']:.3f} | {d['recall']:.3f} | "
                     f"{d['precision']:.3f} | {aupr} | {d['errors']:.1f} | {d['seconds']:.3g} |")
        L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", nargs="?", choices=("snapshot", "render"), default="render")
    ap.add_argument("db", nargs="?", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        ok = PAGE.exists() and PAGE.read_text() == render(json.loads(SNAPSHOT.read_text()))
        if not ok:
            print(f"{PAGE} is out of date")
        return 0 if ok else 1
    if args.command == "snapshot":
        if not args.db:
            print("give the archive path")
            return 2
        SNAPSHOT.write_text(json.dumps(snapshot(args.db), indent=1, sort_keys=True) + "\n")
        print(f"wrote {SNAPSHOT}")
        return 0
    PAGE.write_text(render(json.loads(SNAPSHOT.read_text())))
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
