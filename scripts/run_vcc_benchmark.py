"""
Runs the Virtual Cell Challenge screen benchmark: the settings of ``grid()`` x ``--seeds`` simulations, every algorithm of
``grn_sim.evaluation.vcc_benchmark`` on each. Results are one JSON line per (simulation, algorithm).

    # four shards in parallel, pinned and niced (see the project notes on CPU use), then merge into the bundled file
    for i in 0 1 2 3; do
      env OMP_NUM_THREADS=2 OPENBLAS_NUM_THREADS=1 taskset -c 0-7,32-39 nice -n 10 \
        python scripts/run_vcc_benchmark.py --shard $i/4 --seeds 10 --work /tmp/vcc &
    done; wait
    python scripts/run_vcc_benchmark.py --merge --work /tmp/vcc

Each shard appends to ``<work>/shard<i>.jsonl`` and skips (setting, seed) pairs already there, so a killed run resumes.
``--merge`` writes ``src/grn_sim/data/benchmarks/vcc_screen_benchmark.jsonl`` (what the studio's Virtual Cell tab reads).
"""

from __future__ import annotations

import argparse
import json
import time
import warnings
from pathlib import Path
from typing import List

from grn_sim.evaluation.vcc_benchmark import Setting, algorithm_library, run_simulation

ROOT = Path(__file__).resolve().parents[1]
BUNDLED = ROOT / "src" / "grn_sim" / "data" / "benchmarks" / "vcc_screen_benchmark.jsonl"
REPORT = ROOT / "docs" / "results" / "vcc_screen_benchmark.md"
MARK = {"better": "✓", "marginal": "~", "not_better": "✗", "worse": "✗✗", "control": "·", "reference": "·"}


def _table(rows, factor: str, labels) -> str:
    """Markdown pivot: mean AUPR per algorithm for each level of ``factor`` (mark = verdict against random and hubness)."""
    from grn_sim.evaluation import vcc_benchmark as vb

    levels = vb.factor_levels(rows)[factor]
    aggs = {lv: vb.aggregate(rows, {factor: str(lv)}) for lv in levels}
    algs = [a["algorithm"] for a in vb.aggregate(rows)["algorithms"]]
    head = "| algorithm | " + " | ".join(f"{labels.get(lv, lv)} (n={aggs[lv]['n_simulations']})" for lv in levels) + " |"
    out = [head, "|---|" + "---|" * len(levels)]
    for name in algs:
        cells = []
        for lv in levels:
            a = {x["algorithm"]: x for x in aggs[lv]["algorithms"]}.get(name)
            cells.append("–" if a is None else f"{a['mean']:.3f} {MARK[a['verdict']]}")
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def write_report(rows) -> None:
    from grn_sim.evaluation import vcc_benchmark as vb

    overall = vb.aggregate(rows)
    lines = ["# Virtual Cell screen benchmark", "",
             f"{overall['n_simulations']} simulations in {overall['n_settings']} settings, every algorithm on the same noisy cells "
             "(40 cells per perturbation, calibrated networks, measurement artefacts). Score: AUPR for the true direct edges over the "
             "perturbed genes. Generated by `scripts/run_vcc_benchmark.py --report`; the studio's Virtual Cell tab shows the same "
             "numbers with filters.", "",
             "Verdict marks: ✓ beats the random ranking *and* the hubness-only control (paired Wilcoxon, BH-corrected, q < 0.05, "
             f"lift ≥ {vb.MIN_LIFT}); ~ beats random but not the hubness-only control (ranks hub genes, not pairs); ✗ not better than "
             "random (not appropriate); ✗✗ worse than random; · control.", "", "## All simulations", "",
             "| algorithm | n | AUPR mean ± SD | median | lift vs chance | wins vs random | q vs random | q vs hubness | verdict |",
             "|---|---|---|---|---|---|---|---|---|"]
    for a in overall["algorithms"]:
        lines.append(f"| {a['algorithm']} | {a['n']} | {a['mean']:.3f} ± {a['sd']:.3f} | {a['median']:.3f} | {a['lift']:.1f}× | "
                     f"{a['win_rate']:.0%} | {a['q_value']:.3g} | {a['q_hub']:.3g} | {a['verdict']} |")
    for factor, title, labels in (("pathway", "Pathway architecture", vb.PATHWAYS), ("n_genes", "Network size (genes)", {}),
                                  ("mode", "Perturbation type", vb.MODES), ("pairs", "Double knockouts added", {}),
                                  ("selection", "Selection of perturbed genes (50 % of genes unless full)", vb.SELECTIONS)):
        lines += ["", f"## By {title.lower()}", "", "Mean AUPR (other factors pooled).", "", _table(rows, factor, labels)]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n")
    print("wrote", REPORT)


def grid() -> List[Setting]:
    """One-factor-at-a-time around the baseline, plus the CRISPRi/KO x doubles x selection block and pathways x doubles."""
    base = Setting()
    out = {base.key(): base}

    def add(**kw) -> None:
        s = Setting(**{**base.to_dict(), **kw})
        out.setdefault(s.key(), s)

    for p in ("thesis", "cascade", "feedforward", "lineage", "regulon"):
        add(pathway=p)
    for n in (50, 200):
        add(n_genes=n, pairs=0)
    for m in ("knockout", "input"):
        add(mode=m)
    for sel in ("effective", "random", "expressed", "hubs"):
        add(selection=sel)
    for m in ("knockdown", "knockout"):
        for pairs in (0, 50):
            for sel in ("full", "effective", "random"):
                add(mode=m, pairs=pairs, selection=sel)
    add(pairs=150)
    for p in ("thesis", "cascade", "feedforward", "lineage", "regulon"):
        add(pathway=p, pairs=50)
    add(n_genes=200, pairs=100)
    return list(out.values())


def main() -> None:
    warnings.filterwarnings("ignore")
    ap = argparse.ArgumentParser()
    ap.add_argument("--shard", default="0/1", help="i/N: run every N-th job starting at i")
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--work", default="vcc_work")
    ap.add_argument("--merge", action="store_true")
    ap.add_argument("--report", action="store_true", help="write docs/results/vcc_screen_benchmark.md from the bundled rows")
    ap.add_argument("--list", action="store_true", help="print the grid and exit")
    ap.add_argument("--max-genes", type=int, default=None, help="skip settings above this size (quick runs)")
    a = ap.parse_args()
    work = Path(a.work)
    work.mkdir(parents=True, exist_ok=True)
    settings = grid()
    if a.max_genes:
        settings = [s for s in settings if s.n_genes <= a.max_genes]
    if a.list:
        for s in settings:
            print(s.key())
        print(len(settings), "settings x", a.seeds, "seeds =", len(settings) * a.seeds, "simulations")
        return
    if a.report:
        write_report([json.loads(line) for line in BUNDLED.read_text().splitlines() if line.strip()])
        return
    if a.merge:
        rows = []
        for f in sorted(work.glob("shard*.jsonl")):
            rows += [json.loads(line) for line in f.read_text().splitlines() if line.strip()]
        BUNDLED.parent.mkdir(parents=True, exist_ok=True)
        BUNDLED.write_text("\n".join(json.dumps(r, separators=(",", ":")) for r in rows) + "\n")
        print(f"merged {len(rows)} rows -> {BUNDLED}")
        return
    i, n_shards = (int(x) for x in a.shard.split("/"))
    jobs = [(s, seed) for seed in range(1, a.seeds + 1) for s in settings]
    mine = jobs[i::n_shards]
    out = work / f"shard{i}.jsonl"
    done = set()
    for f in work.glob("shard*.jsonl"):
        for line in f.read_text().splitlines():
            if line.strip():
                r = json.loads(line)
                done.add((Setting(**{k: r[k] for k in Setting.__dataclass_fields__}).key(), r["seed"]))
    algorithms = algorithm_library()
    for k, (s, seed) in enumerate(mine, 1):
        if (s.key(), seed) in done:
            continue
        t = time.time()
        rows = run_simulation(s, seed, algorithms)
        with out.open("a") as fh:
            for r in rows:
                fh.write(json.dumps(r, separators=(",", ":")) + "\n")
        print(f"[{i}/{n_shards}] {k}/{len(mine)} {s.key()} seed {seed}: {time.time() - t:.0f} s", flush=True)


if __name__ == "__main__":
    main()
