"""Renders docs/results/algorithm_runtimes.md: how long every registered algorithm takes, by network size.

Every number is read from stored data (nothing is measured here): ``archive_leaderboard.json`` (median run time over the archived
runs of a size group, 1.0.5 archive), ``audit_100_250.json`` (one fresh process per algorithm at 100 and 250 genes) and
``timings_500/audit_modular_500.json`` (the same at 500 genes, with peak memory). ``tests/test_runtimes_doc.py`` fails when the page
and the data differ.

    python scripts/render_runtimes.py            # rewrite the page
    python scripts/render_runtimes.py --check    # exit 1 when the page is out of date
"""
import argparse
import json
import math
import sys
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
RES = ROOT / "docs" / "results"
PAGE = RES / "algorithm_runtimes.md"


def fmt(s: Optional[float]) -> str:
    """Seconds as a reader wants them: milliseconds, seconds, minutes or hours."""
    if s is None:
        return "-"
    if s < 0.01:
        return "<0.01 s"
    if s < 10:
        return f"{s:.2f} s"
    if s < 100:
        return f"{s:.0f} s"
    if s < 3600:
        return f"{s / 60:.1f} min"
    return f"{s / 3600:.1f} h"


def band(s: Optional[float]) -> str:
    if s is None:
        return "-"
    return "instant" if s < 1 else "seconds" if s < 30 else "minutes" if s < 600 else "tens of minutes or more"


def render() -> str:
    from grn_sim.inference import registry
    groups = json.loads((RES / "archive_leaderboard.json").read_text())["groups"]
    audit = json.loads((RES / "audit_100_250.json").read_text())["runs"]
    a500 = {r["alg"]: r for r in json.loads((RES / "timings_500" / "audit_modular_500.json").read_text()) if "error" not in r}
    a100 = {r["alg"]: r for r in audit["100"]}
    a250 = {r["alg"]: r for r in audit["250"]}

    def arch(group: str, alg: str) -> Optional[float]:
        d = groups[group]["algorithms"].get(alg)
        return d["seconds"] if d else None

    n500, n1000 = groups["500"]["runs"], groups["1000"]["runs"]
    rows = []
    for spec in registry.specs():
        k = spec.key
        t100, t250 = (a100.get(k) or {}).get("seconds"), (a250.get(k) or {}).get("seconds")
        t500 = (a500.get(k) or {}).get("seconds")
        t500a, t1000 = arch("500", k), arch("1000", k)
        growth = math.log2(t1000 / t500a) if t1000 and t500a and t500a > 0.05 else None
        mem = (a500.get(k) or {}).get("extra_mb")
        rows.append((k, arch("small", k), t100, t250, t500, t500a, t1000, growth, mem))
    rows.sort(key=lambda r: (r[5] if r[5] is not None else 0.0))
    L = ["# How long each algorithm takes", "",
         "Generated by `scripts/render_runtimes.py` from stored results (`archive_leaderboard.json`, `audit_100_250.json`, "
         "`timings_500/audit_modular_500.json`); `tests/test_runtimes_doc.py` fails when this page and the data differ. Rows are ordered "
         "from fastest to slowest at 500 genes.", "",
         "## What the numbers are", "",
         "- **Time** is the algorithm's own fit time on one network, the figure the studio shows as run time (an ensemble's time includes "
         "its members). It excludes simulating the network, scoring and drawing; a run in the studio or the job queue adds those, and "
         "simulating a network takes seconds up to a minute or two at 500 genes.",
         "- **Where they come from:** *up to 16 genes* and *500 / 1000 genes (archive)*: the median over the archived runs of that size "
         f"(471, {n500} and {n1000} runs; the 1000-gene column is a single run). *100 / 250 / 500 genes (audit)*: one fresh process per "
         "algorithm on one `replogle_like` modular network (not isolated from other load on the machine, so single entries can be off by a factor of two).",
         "- **Machine:** AMD Threadripper 2990WX (64 threads), BLAS pinned to one thread, process pools up to 16 workers for the algorithms "
         "that have one (S2G, G2S, the voting ensembles, GENIE3, GRNBoost-lite, NIR). A laptop with fewer cores will be slower by about "
         "the core ratio for those; the others are single-threaded. Concurrent jobs slow each other down; a busy machine can double a time.",
         "- **Growth** is the exponent between the 500- and 1000-gene archive medians (time ~ genes^growth); 3 means doubling the genes "
         "multiplies the time by 8. Use it to extrapolate cautiously: the project's scope stops at 500 genes.", "",
         "## Table", "",
         "| algorithm | up to 16 genes | 100 genes | 250 genes | 500 genes (audit) | 500 genes (archive) | 1000 genes (archive) | growth | extra memory at 500 | speed class at 500 |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for k, small, t100, t250, t500, t500a, t1000, growth, mem in rows:
        L.append(f"| `{k}` | {fmt(small)} | {fmt(t100)} | {fmt(t250)} | {fmt(t500)} | {fmt(t500a)} | {fmt(t1000)} | "
                 f"{'-' if growth is None else f'{growth:.1f}'} | {'-' if mem is None else f'{mem} MB'} | {band(t500a)} |")
    slow = [r for r in rows if r[5] is not None and r[5] >= 10]
    L += ["", "## Reading", "",
          "- **Up to 16 genes everything is instant** (the slowest, GRNBoost-lite, takes under a second), so the whole leaderboard of the "
          "studio and the sweeps cost seconds per network.",
          "- **At 500 genes the cost splits in two groups.** " + (", ".join(f"`{r[0]}`" for r in rows if (r[5] or 0) < 10)) +
          " finish in under 10 s each. " + (", ".join(f"`{r[0]}`" for r in slow)) + " take 10 s to a few minutes; all of them together "
          "need roughly " + fmt(sum(r[5] or 0.0 for r in rows)) + " per network (archive medians), most of it in the voting ensembles, GRNBoost-lite, "
          "NIR and GENIE3.",
          "- **The steepest growth is NOTEARS** (a matrix-exponential constraint) and G2S; at 1000 genes NOTEARS needs about "
          + fmt(groups["1000"]["algorithms"]["notears"]["seconds"]) + " and the voting ensembles about "
          + fmt(groups["1000"]["algorithms"]["vote"]["seconds"]) + ".",
          "- **Memory** at 500 genes stays within about 1.5 GB above the process baseline for every algorithm (CellBox is the largest).",
          "- Times of the stored results come from the code of their time; FAST and GRNBoost-lite were recomputed for 1.0.5, CellBox only up "
          "to 266 genes (see CHANGELOG), so a few 500- and 1000-gene entries differ from the audit column. Use the order of magnitude.", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        return 0 if PAGE.exists() and PAGE.read_text() == text else 1
    PAGE.write_text(text)
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
