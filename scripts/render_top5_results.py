"""Renders docs/results/mechanistic_vs_statistical_top5.md from the Virtual Cell screen corpus.

Every number on the page is computed from ``src/grn_sim/data/benchmarks/vcc_screen_benchmark.jsonl`` (one row per simulation
and algorithm); ``tests/test_top5_results_doc.py`` fails when the committed page differs from a fresh render.

    python scripts/render_top5_results.py            # rewrite the page
    python scripts/render_top5_results.py --check    # exit 1 when the page is out of date
"""
import argparse
import collections
import json
import math
import statistics as st
import sys
from pathlib import Path
from typing import Any, Dict, List, Sequence

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "src" / "grn_sim" / "data" / "benchmarks" / "vcc_screen_benchmark.jsonl"
PAGE = ROOT / "docs" / "results" / "mechanistic_vs_statistical_top5.md"
CONTROLS = ("random", "gene_features")
MECHANISTIC = "mechanistic"
STATISTICAL = ("linear_sem", "nonlinear_scm", "nb_copula", "boolean")
GENERATOR_NAMES = {"linear_sem": "linear SEM", "nonlinear_scm": "nonlinear additive-noise SCM",
                   "nb_copula": "negative-binomial copula", "boolean": "probabilistic Boolean network",
                   "mechanistic": "mechanistic (Hill kinetics)"}


def load(path: Path = CORPUS) -> List[Dict[str, Any]]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def summarise(rows: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Per algorithm (controls excluded), best AUPR first."""
    by: Dict[str, List[Dict[str, Any]]] = collections.defaultdict(list)
    for r in rows:
        by[r["algorithm"]].append(r)
    out = []
    for algorithm, rs in by.items():
        if algorithm in CONTROLS:
            continue
        x = [r["aupr_direct"] for r in rs]
        n, mean, sd = len(x), st.mean(x), st.stdev(x)
        out.append({"algorithm": algorithm, "n": n, "mean": mean, "sd": sd, "ci": 1.96 * sd / math.sqrt(n),
                    "median": st.median(x), "lift": mean / st.mean(r["base_direct"] for r in rs),
                    "pk": st.mean(r["p_at_k_direct"] for r in rs), "total": st.mean(r["aupr_total"] for r in rs),
                    "seconds": st.median(r["seconds"] for r in rs)})
    out.sort(key=lambda t: (-t["mean"], t["algorithm"]))
    return out


def reference_levels(rows: Sequence[Dict[str, Any]]) -> Dict[str, float]:
    by: Dict[str, List[float]] = collections.defaultdict(list)
    for r in rows:
        if r["algorithm"] in CONTROLS:
            by[r["algorithm"]].append(r["aupr_direct"])
    levels = {a: st.mean(v) for a, v in by.items()}
    levels["chance"] = st.mean(r["base_direct"] for r in rows if r["algorithm"] == "random")
    return levels


def table(summary: Sequence[Dict[str, Any]], top: int) -> List[str]:
    lines = ["| # | algorithm | AUPR direct, mean ± SD | 95% CI | median | lift | P@k | AUPR total | median s |",
             "|---|---|---|---|---|---|---|---|---|"]
    for i, t in enumerate(summary[:top], 1):
        lines.append(f"| {i} | {t['algorithm']} | {t['mean']:.3f} ± {t['sd']:.3f} | {t['mean'] - t['ci']:.3f}–{t['mean'] + t['ci']:.3f} "
                     f"| {t['median']:.3f} | {t['lift']:.1f}× | {t['pk']:.3f} | {t['total']:.3f} | {t['seconds']:.2f} |")
    return lines


def render(rows: Sequence[Dict[str, Any]]) -> str:
    mech = [r for r in rows if r["generator"] == MECHANISTIC]
    stat = [r for r in rows if r["generator"] in STATISTICAL]
    s_mech, s_stat = summarise(mech), summarise(stat)
    lv_mech, lv_stat = reference_levels(mech), reference_levels(stat)
    sims = {g: len({(r["seed"], r["noise"], r["pathway"], r["n_genes"], r["mode"], r["pairs"], r["selection"], r["fraction"])
                    for r in rows if r["generator"] == g and r["algorithm"] == "random"}) for g in (MECHANISTIC,) + STATISTICAL}
    one = [r for r in rows if r["algorithm"] == "random"]
    modes = collections.Counter(r["mode"] for r in one)
    sizes = collections.Counter(r["n_genes"] for r in one)
    cells = sorted({r["cells"] for r in one})

    rank_m = {t["algorithm"]: i for i, t in enumerate(s_mech)}
    rank_s = {t["algorithm"]: i for i, t in enumerate(s_stat)}
    common = sorted(rank_m)
    n = len(common)
    rho = 1 - 6 * sum((rank_m[a] - rank_s[a]) ** 2 for a in common) / (n * (n * n - 1))
    moved = sorted(common, key=lambda a: (-abs(rank_m[a] - rank_s[a]), a))[:5]
    shared = [t["algorithm"] for t in s_mech[:5] if t["algorithm"] in {u["algorithm"] for u in s_stat[:5]}]

    L: List[str] = []
    L += ["# Inference on mechanistic and on statistical data: the top 5 algorithms",
          "",
          "Generated by `scripts/render_top5_results.py` from `src/grn_sim/data/benchmarks/vcc_screen_benchmark.jsonl` "
          "(the Virtual Cell screen corpus behind `vcc_screen_benchmark.md`); a test fails if this page and the data differ. "
          "Nothing here is typed in by hand except the wording.",
          "",
          "## What is compared",
          "",
          f"- **Corpus:** {len(rows):,} rows, one per simulated screen and algorithm; {len(one):,} screens, "
          f"{sims[MECHANISTIC]} per generator.",
          f"- **Mechanistic:** the Hill-kinetics engine of the studio ({sims[MECHANISTIC]} screens).",
          f"- **Statistical:** four statistical generators pooled ({sum(sims[g] for g in STATISTICAL)} screens): "
          + ", ".join(GENERATOR_NAMES[g] for g in STATISTICAL) + ".",
          "- **Settings (all generators together):** perturbation mode " + ", ".join(f"{m} {c}" for m, c in sorted(modes.items()))
          + "; genes " + ", ".join(f"{g} ({c})" for g, c in sorted(sizes.items())) + "; cells per perturbation "
          + ", ".join(str(c) for c in cells) + ". Noise level, size, perturbation type and pathway architecture are pooled.",
          "- **Measure:** AUPR against the direct edges (`aupr_direct`). *lift* = mean AUPR / mean chance AUPR; *P@k* = precision at "
          "the true number of edges; *AUPR total* = AUPR against total (direct plus indirect) effects; *median s* = median run "
          "time of the algorithm on one screen. The ± is the SD across screens; the 95% CI is 1.96 SD/√n for the mean "
          "(a normal approximation, not a paired test).",
          "- **Ranked:** the 20 algorithms; the controls (`random`, `gene_features`) are shown as reference levels, not ranked.",
          "",
          "## Mechanistic data",
          "",
          f"{s_mech[0]['n']} screens per algorithm. Chance AUPR {lv_mech['chance']:.3f}; controls: "
          f"gene_features {lv_mech['gene_features']:.3f}, random {lv_mech['random']:.3f}.",
          ""]
    L += table(s_mech, 5)
    L += ["", "## Statistical data (four generators pooled)", "",
          f"{s_stat[0]['n']} screens per algorithm. Chance AUPR {lv_stat['chance']:.3f}; controls: "
          f"gene_features {lv_stat['gene_features']:.3f}, random {lv_stat['random']:.3f}.", ""]
    L += table(s_stat, 5)
    L += ["", "### Each statistical generator (top 3)", ""]
    for g in STATISTICAL:
        sub = summarise([r for r in rows if r["generator"] == g])
        L += [f"**{GENERATOR_NAMES[g]}** ({sub[0]['n']} screens per algorithm)", ""] + table(sub, 3) + [""]
    L += ["## Comparison", "",
          f"- Best mean AUPR: mechanistic {s_mech[0]['algorithm']} {s_mech[0]['mean']:.3f}, statistical {s_stat[0]['algorithm']} "
          f"{s_stat[0]['mean']:.3f}. Spread across screens (SD of the best five): mechanistic "
          f"{min(t['sd'] for t in s_mech[:5]):.3f}–{max(t['sd'] for t in s_mech[:5]):.3f}, statistical "
          f"{min(t['sd'] for t in s_stat[:5]):.3f}–{max(t['sd'] for t in s_stat[:5]):.3f}.",
          f"- Rank agreement over the {n} algorithms: Spearman ρ = {rho:.2f}. The two top 5 share "
          + (", ".join(shared) if shared else "none") + ".",
          "- Largest rank changes (mechanistic → statistical): "
          + "; ".join(f"{a} {rank_m[a] + 1} → {rank_s[a] + 1}" for a in moved) + ".", "",
          "## Limits of this page", "",
          "- The corpus is simulated Perturb-seq screens, not the 500-2000 gene studio runs of `SCALE_BENCHMARK.md`, and most of its "
          "screens use knockdown perturbations, where the perturbed gene's own response is visible. Algorithms that need that "
          "(CellBox) rank high here and do not on the regulator-input data of the scale runs.",
          "- It predates the algorithm fixes of 2026-11-12 (inspre in regulator mode, X + U for the co-expression methods, K per "
          "target): those matter mainly for regulator-input data, so a re-run of the corpus would show their effect. It was not re-run.",
          "- Screens differ in noise, size, perturbation type and architecture, which are pooled here; the per-factor tables are in "
          "`vcc_screen_benchmark.md`. The CIs treat screens as independent, which they are not entirely (10 seeds per setting).",
          ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed page is out of date")
    args = ap.parse_args()
    text = render(load())
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != text:
            print(f"{PAGE} is out of date: run scripts/render_top5_results.py")
            return 1
        return 0
    PAGE.write_text(text)
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
