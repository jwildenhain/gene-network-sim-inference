"""Held-out-perturbation prediction on simulated screens (see grn_sim.evaluation.heldout_screen).

    python scripts/heldout_screen_benchmark.py [--sizes 100 200] [--seeds 5] [--out docs/results/heldout_screen_benchmark]

Writes ``<out>.json`` (every simulation) and ``<out>.md`` (means and standard deviations over seeds). Settings are the Virtual
Cell tab's defaults: medium noise, CRISPRi knockdown, 40 cells per perturbation, every gene perturbed.
"""
from __future__ import annotations

import argparse
import json
import warnings
from pathlib import Path

import numpy as np

from grn_sim.evaluation import screen_benchmark as sb
from grn_sim.evaluation import vcc_benchmark as vb
from grn_sim.evaluation.heldout_screen import METRICS, PREDICTORS, evaluate_heldout

GENERATORS = ("linear_sem", "nb_copula", "nonlinear_scm")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sizes", type=int, nargs="+", default=[100, 200])
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--out", default="docs/results/heldout_screen_benchmark")
    a = ap.parse_args()
    warnings.simplefilter("ignore")
    runs = []
    for g in GENERATORS:
        for n in a.sizes:
            for seed in range(a.seeds):
                run = vb.simulate_screen(vb.Setting(generator=g, n_genes=n), seed)
                ace = sb.screen_inputs(run, "cells", seed, normalisation=vb.NORMALISATION)
                runs.append({"generator": g, "n_genes": n, "seed": seed, **evaluate_heldout(run.screen, ace, seed=seed)})
                print(g, n, seed, flush=True)
    out = Path(a.out)
    out.with_suffix(".json").write_text(json.dumps(runs, indent=1, allow_nan=True) + "\n")
    out.with_suffix(".md").write_text(render(runs))
    print("wrote", out.with_suffix(".md"))
    return 0


def _ms(vals):
    v = np.array([x for x in vals if np.isfinite(x)], dtype=float)
    return "-" if not len(v) else f"{v.mean():.3f} ± {v.std(ddof=1) if len(v) > 1 else 0.0:.3f}"


def render(runs) -> str:
    seeds = len({r["seed"] for r in runs})
    lines = ["# Held-out perturbation prediction on simulated screens", "",
             "Generated by `scripts/heldout_screen_benchmark.py` (method and metrics: `grn_sim.evaluation.heldout_screen`). Each simulated "
             "screen perturbs every gene once; 5-fold cross-validation over the perturbed genes; the predictors see responses estimated "
             "from the simulated cells and are scored against the noise-free total effects, on off-target genes only. "
             f"Mean ± standard deviation over {seeds} seeds; medium noise, CRISPRi knockdown, 40 cells per perturbation.", "",
             "Metrics: `pearson_delta` correlation of predicted and true response; `deg_mse_skill` 1 - MSE/MSE(no effect) on the genes the "
             "perturbation truly moved (above 0 beats predicting no effect); `direction` share with the right sign; `top_overlap` share of "
             "the truly affected genes among the k largest predicted effects. `silent` perturbations move no off-target gene; "
             "only `active` ones (at least one moved gene) have all four metrics.", ""]
    for g in GENERATORS:
        for n in sorted({r["n_genes"] for r in runs}):
            sel = [r for r in runs if r["generator"] == g and r["n_genes"] == n]
            if not sel:
                continue
            active = np.mean([r["control"]["active"]["n"] for r in sel])
            lines += [f"## {g}, {n} genes", "", f"Held-out perturbations per simulation: {sel[0]['n_perturbations']}, of which active on average {active:.1f}.", "",
                      "| predictor | stratum | " + " | ".join(METRICS) + " |", "|---|---|" + "---|" * len(METRICS)]
            for m in PREDICTORS:
                for stratum in ("all", "active"):
                    lines.append(f"| {m} | {stratum} | " + " | ".join(_ms([r[m][stratum][k] for r in sel]) for k in METRICS) + " |")
            lines.append("")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
