"""
Why FAST ranked low, measured: the effect of the identity in its first estimate.

FAST estimates ``A_0 = (x - u) X^+``, which is ``I + A`` for a full-rank X, so each row's largest entry is its own diagonal and the
top-K selection spends a slot on a self-edge. ``FastSVD(rank_without_identity=True)`` ranks by ``|A_0 - I|`` without the diagonal.
Compared on the studio's own code path (``_execute_inference``) with NIR as the reference:

    python scripts/diagnose_fast.py --genes 50 100 --seeds 6 --out docs/results/fast_diagnosis.json
    python scripts/diagnose_fast.py --render docs/results/fast_diagnosis.md       # the page, from the JSON

Variants: ``matlab`` (the MATLAB-identical ranking), ``no_identity`` (the studio's setting), each with and without the per-row
BIC choice of the model order (``adaptive_k``, which the studio uses on Hill data); data: the Hill engine (regulator input) and the
linear engine (additive perturbation).
"""
from __future__ import annotations

import argparse
import json
import warnings
from collections import defaultdict
from typing import Any, Dict

import numpy as np

from grn_sim.inference import registry
from grn_sim.inference.fast_svd import FastSVD
from grn_sim.inference.registry import AlgorithmSpec
from grn_sim.web import server

VARIANTS = {
    "fast_matlab": dict(rank_without_identity=False, adaptive_k=None),
    "fast_no_identity": dict(rank_without_identity=True, adaptive_k=None),
    "fast_matlab_fixed_k": dict(rank_without_identity=False, adaptive_k=False),
    "fast_no_identity_fixed_k": dict(rank_without_identity=True, adaptive_k=False),
}


def _register_variants() -> None:
    for key, kw in VARIANTS.items():
        def build(c, kw=kw):
            adaptive = c.use_reg if kw["adaptive_k"] is None else kw["adaptive_k"]
            return FastSVD(k_interactions=c.k_est, perturbation_mode="regulator" if c.use_reg else "additive",
                           adaptive_k=adaptive, rank_without_identity=kw["rank_without_identity"])
        registry.register(AlgorithmSpec(key, key, build, regulator_input=True, negate_u_in_additive=True,
                                        additive_target_regulator=True), replace=True)


def run(genes: int, seeds: int, engine: str) -> Dict[str, Any]:
    keys = list(VARIANTS) + ["nir", "ridge_cv"]
    acc: Dict[str, list] = defaultdict(list)
    for seed in range(seeds):
        req = {"num_genes": genes, "topology": "modular", "seed": seed, "calibration_preset": "replogle_like"}
        if engine == "linear":
            req["kinetics_engine"] = "linear_jacobian"
        server._execute_simulation(req)
        metrics = server._execute_inference(keys)["metrics"]
        for k in keys:
            m = metrics[k]
            acc[k].append([m["f1_score"], m["aupr"], m["recall"], m["precision"]])
    out = {}
    for k, v in acc.items():
        a = np.array(v)
        out[k] = {"f1": float(a[:, 0].mean()), "f1_sd": float(a[:, 0].std(ddof=1)) if len(a) > 1 else 0.0,
                  "aupr": float(a[:, 1].mean()), "recall": float(a[:, 2].mean()), "precision": float(a[:, 3].mean())}
    return out


LABELS = {"fast_matlab": "FAST, MATLAB ranking (adaptive K on Hill data)", "fast_no_identity": "FAST, identity removed (the studio)",
          "fast_matlab_fixed_k": "FAST, MATLAB ranking, fixed K", "fast_no_identity_fixed_k": "FAST, identity removed, fixed K",
          "nir": "NIR (reference)", "ridge_cv": "RidgeCV (reference)"}
ENGINES = {"hill": "Hill kinetics engine (regulator-input perturbation, the studio's default)",
           "linear": "linear engine (additive perturbation, A X = -U)"}


def render(result: Dict[str, Any]) -> str:
    L = ["# Why FAST ranked low", "",
         "Generated by `scripts/diagnose_fast.py --render` from `docs/results/fast_diagnosis.json`; `tests/test_fast_identity.py` fails when "
         "the page and the data differ.", "",
         "## The cause", "",
         "FAST estimates `A_0 = (x - u) X^+`. For a full-rank X, `X X^+ = I`, so `A_0 = I + A`: the diagonal of every row is about 1 and "
         "is the largest entry of the row. Step 4 keeps the K largest entries per row and refits them, so one of the K slots of every row "
         "goes to a self-edge that is not in the network (the simulated ground truth has no self-regulation, and the scorer counts a "
         "predicted self-edge as a false positive). With K at the network's mean in-degree (2 to 3) that removes a third to a half of the "
         "regulators FAST could find. The rank-(N-1) "
         "truncation also leaves `I - X X^+` noise on the diagonal, so subtracting the identity alone is not enough: the corrected ranking "
         "uses `|A_0 - I|` and never selects the diagonal.", "",
         "The identity is right for the E. coli SOS data (fast.m adds it back when N = 9), which is why the MATLAB code has it; "
         "`FastSVD(rank_without_identity=False)` is that MATLAB-identical selection and stays the class default (the equivalence tests "
         "pin it). The registry, hence the studio, the job queue, the archive and the sweeps, uses `rank_without_identity=True`; where the "
         "diagonal correction is already on (SOS) the option changes nothing.", "",
         f"## Measured ({result['seeds']} seeds per row, modular networks, `replogle_like` preset, studio code path)", "",
         "F1 at the algorithm's own edge count (mean ± sd over seeds), AUPR, recall, precision.", ""]
    for run in result["runs"]:
        L += [f"### {run['genes']} genes, {ENGINES[run['engine']]}", "", "| method | F1 | AUPR | recall | precision |", "|---|---|---|---|---|"]
        for k, v in run["methods"].items():
            L.append(f"| {LABELS.get(k, k)} | {v['f1']:.3f} ± {v['f1_sd']:.3f} | {v['aupr']:.3f} | {v['recall']:.3f} | {v['precision']:.3f} |")
        L.append("")
    L += ["## Reading", "",
          "- On Hill data (the studio's default) dropping the identity lifts FAST from F1 0.35 to 0.45 at 50 genes and from 0.28 to 0.35 at 100, "
          "to the level of NIR (0.45 and 0.37) and above it in AUPR at 50 genes. The adaptive per-row model order (BIC) adds a little on top.",
          "- On the linear engine the gain is real but small in absolute terms (0.12 to 0.16 at 50 genes, 0.03 to 0.05 at 100) and FAST stays "
          "well below NIR: the remaining gap is the unregularised truncated-SVD inverse of a noisy, ill-conditioned X. Larger SVD damping "
          "(`svd_reg` 1e-3 to 3e-1) was tried and did not help on Hill data (F1 0.43 down to 0.34-0.36) and moved the linear case by less than the "
          "seed spread, so it was left at 1e-6.",
          "- The archive's FAST rows and the leaderboards were recomputed with the corrected ranking (see CHANGELOG 1.0.5); numbers quoted "
          "from earlier releases for FAST are from the MATLAB ranking.", ""]
    return "\n".join(L)


def main() -> None:
    warnings.filterwarnings("ignore")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--genes", type=int, nargs="+", default=[50, 100])
    ap.add_argument("--seeds", type=int, default=6)
    ap.add_argument("--out", default="")
    ap.add_argument("--render", default="", help="write the page from an existing --out JSON instead of running")
    args = ap.parse_args()
    if args.render:
        with open(args.out or "docs/results/fast_diagnosis.json") as fh:
            text = render(json.load(fh))
        with open(args.render, "w") as fh:
            fh.write(text + "\n")
        return
    _register_variants()
    result = {"seeds": args.seeds, "runs": []}
    for engine in ("hill", "linear"):
        for n in args.genes:
            result["runs"].append({"engine": engine, "genes": n, "methods": run(n, args.seeds, engine)})
            print(json.dumps(result["runs"][-1]), flush=True)
    if args.out:
        with open(args.out, "w") as fh:
            json.dump(result, fh, indent=1)


if __name__ == "__main__":
    main()
