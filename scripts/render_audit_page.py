"""Renders docs/results/audit_100_250.md from docs/results/audit_100_250.json (``scripts/audit_algorithms.py`` output).

Every number on the page is read from the JSON; ``tests/test_audit_page_doc.py`` fails when the page and the JSON differ.

    python scripts/render_audit_page.py            # rewrite the page
    python scripts/render_audit_page.py --check    # exit 1 when the page is out of date
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs" / "results" / "audit_100_250.json"
PAGE = ROOT / "docs" / "results" / "audit_100_250.md"


def render(d: dict) -> str:
    setup = d["setup"]
    L = ["# Algorithm audit at 100 and 250 genes: time, memory, accuracy", "",
         "Generated by `scripts/render_audit_page.py` from `docs/results/audit_100_250.json` (the output of "
         "`scripts/audit_algorithms.py`); a test fails if this page and the data differ.", "",
         f"- **Network:** {setup['topology']} topology, seed {setup['seed']}, calibration preset `{setup['calibration_preset']}`; "
         f"archived as {', '.join(f'`{v}` ({k} genes)' for k, v in setup['archived_as'].items())}.",
         f"- **Environment:** {setup['environment']}. Time is the algorithm's own run time; *extra MB* is the growth of the "
         "process's peak memory while it ran; *predicted* is the number of edges it returns.",
         "- **Single run per size:** no seed variance was measured. Run times of the fast algorithms are dominated by start-up and "
         "by whatever else the machine was doing (GRNBoost took 56 s in the first 250-gene pass and 10 s when repeated alone, "
         "while other jobs were using the cores).", ""]
    for size, rows in d["runs"].items():
        total = sum(r["seconds"] for r in rows)
        L += [f"## {size} genes", "",
              f"{len(rows)} algorithms, {rows[0]['true_edges']} true edges; the times add up to {total:.0f} s.", "",
              "| algorithm | time s | extra MB | peak MB | recall | precision | F1 | AUPR | predicted |",
              "|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(rows, key=lambda r: (-r["f1"], r["alg"])):
            L.append(f"| {r['alg']} | {r['seconds']:.2f} | {r['extra_mb']} | {r['peak_mb_after']} | {r['recall']:.3f} | "
                     f"{r['precision']:.3f} | {r['f1']:.3f} | {r['aupr']:.3f} | {r['predicted']} |")
        L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(json.loads(DATA.read_text()))
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != text:
            print(f"{PAGE} is out of date: run scripts/render_audit_page.py")
            return 1
        return 0
    PAGE.write_text(text)
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
